CACHE = os.path.expanduser("~/.cache/game-ui/fonts")


# --------------------------------------------------------------------------- tokens

def build_tokens(P):
    spec, b = P["spec"], P["brief"]; U = spec["ui"]
    base = L.base_palette(spec)
    derived = {k: L.resolve_color(v, base) for k, v in b.get("color", {}).items()}
    color = dict(base); color.update(derived)
    roles = {}
    for name, r in b.get("roles", {}).items():
        fg, bg = color[r["fg"]], color[r["bg"]]
        roles[name] = dict(r, fg_hex=fg, bg_hex=bg, contrast=round(L.contrast(fg, bg), 2))
    fams = {}
    for k, f in U["type"]["families"].items():
        fams[k] = {"family": f["family"], "files": ["fonts/" + x for x in f["files"]], "fallback": "Arial Narrow, sans-serif" if k == "state" else "Courier New, monospace"}
        for x in ("axes", "numerals", "case"):
            if x in f: fams[k][x] = f[x]
    out = {
        "format": "ig_ui_tokens", "version": 1, "id": "ui_tokens",
        "source": "assets/spec.json ui (palette, type, space, stroke) + assets/src/ui/tokens/ui_tokens/brief.json (roles, motion, treatments). Generated by game-ui; edit the sources, not this file.",
        "base": base, "derived": b.get("color", {}), "color": color, "roles": roles,
        "type": {"families": fams, "scale": U["type"]["scale"], "min_px": U["type"]["min_px"]},
        "space_px": U["space_px"], "stroke_px": U["stroke_px"],
        "icon": {k: U["icon"][k] for k in ("grid_u", "export_px", "densities", "min_legible_px", "variants")},
        "motion": b.get("motion", {}), "crt": b.get("crt", {}), "paper": b.get("paper", {}), "rebel": b.get("rebel", {}),
        "never": U.get("never", []),
    }
    os.makedirs(P["export_dir"], exist_ok=True)
    L.write_json(P["json"], out)
    # CSS custom properties for the DOM client
    css = ["/* generated by game-ui from ui_tokens.json -- do not edit */", ":root {"]
    for k, v in color.items(): css.append("  --ui-%s: %s;" % (k.replace("_", "-"), v))
    for k, f in fams.items(): css.append("  --ui-font-%s: \"%s\", %s;" % (k, f["family"], f["fallback"]))
    for i, s in enumerate(U["space_px"]): css.append("  --ui-space-%d: %dpx;" % (i, s))
    for k, s in U["type"]["scale"].items():
        css.append("  --ui-%s: %d %dpx/%s var(--ui-font-%s);" % (k.replace("_", "-"), s["weight"], s["size"], s["line"], s["family"]))
        css.append("  --ui-%s-tracking: %sem;" % (k.replace("_", "-"), s["tracking_em"]))
    css.append("}")
    faces = []
    for k, f in U["type"]["families"].items():
        for fn in f["files"]:
            if not fn.endswith(".woff2"): continue
            w = "100 900" if "wght" in fn else ("700" if "Bold" in fn else "400")
            st = "italic" if "Italic" in fn else "normal"
            faces.append("@font-face { font-family: \"%s\"; src: url(fonts/%s) format(\"woff2\"); font-weight: %s; font-style: %s; font-display: block; }" % (f["family"], fn, w, st))
    for k, s in U["type"]["scale"].items():
        cls = ".ui-%s { font: var(--ui-%s); letter-spacing: var(--ui-%s-tracking);%s%s }" % (
            k.replace("_", "-"), k.replace("_", "-"), k.replace("_", "-"), " text-transform: uppercase;" if s.get("case") == "upper" else "",
            " font-variant-numeric: tabular-nums;" if s["family"] == "state" else "")
        faces.append(cls)
    open(os.path.join(P["export_dir"], "ui_tokens.css"), "w").write("\n".join(css + faces) + "\n")
    return out


# --------------------------------------------------------------------------- fonts

def _fetch(url, dst):
    import urllib.request
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    if not os.path.exists(dst): urllib.request.urlretrieve(url, dst)
    return dst


def build_fonts(P):
    from fontTools import subset
    from fontTools.ttLib import TTFont
    b = P["brief"]; out_dir = P["export_dir"]; os.makedirs(out_dir, exist_ok=True)
    if b.get("build") == "script": return build_script(P)   # drawn lettering (ig_ui_chalkfont): build_<id>.py, no font files
    files = []; lic_done = set()
    for f in b["fonts"]:
        src = _fetch(f["url"], os.path.join(CACHE, f["file"]))
        dst = os.path.join(out_dir, f["file"]); shutil.copyfile(src, dst)
        lic_name = "OFL_" + f["family"].replace(" ", "") + ".txt"
        if lic_name not in lic_done:
            _fetch(f["license_url"], os.path.join(CACHE, lic_name)); shutil.copyfile(os.path.join(CACHE, lic_name), os.path.join(out_dir, lic_name)); lic_done.add(lic_name)
        w2 = os.path.splitext(f["file"])[0] + ".woff2"
        opts = subset.Options(); opts.flavor = "woff2"; opts.layout_features = ["*"]; opts.name_IDs = ["*"]; opts.notdef_outline = True
        font = TTFont(src); sub = subset.Subsetter(opts)
        sub.populate(unicodes=subset.parse_unicodes(b["subset"]["unicodes"])); sub.subset(font)
        font.flavor = "woff2"; font.save(os.path.join(out_dir, w2))
        for fn in (f["file"], w2):
            p = os.path.join(out_dir, fn)
            files.append({"file": fn, "family": f["family"], "role": f["role"], "weight": f.get("weight", "100-900" if "wght" in fn else 400),
                          "style": f.get("style", "normal"), "bytes": os.path.getsize(p), "sha256": hashlib.sha256(open(p, "rb").read()).hexdigest()[:16],
                          "license": "SIL OFL 1.1", "license_file": lic_name, "copyright": f["copyright"], "source": f["url"]})
    out = {"format": "ig_ui_fonts", "version": 1, "id": "ui_fonts", "files": files,
           "note": "TTF for Godot (FontFile) and tools; WOFF2 subsets (Latin, Latin-1, Latin Extended-A) for the browser. OFL text ships beside the fonts."}
    L.write_json(P["json"], out); return out


# --------------------------------------------------------------------------- iconset

def build_iconset(P):
    import numpy as np
    import ui_icons as I
    spec, b = P["spec"], P["brief"]; U = spec["ui"]; IC = U["icon"]
    toks = L.load_tokens(P["root"], spec)
    G, meta, aliases = I.load_glyphs(os.path.join(P["dir"], b.get("glyphs", "glyphs.py")), IC["grid_u"], IC["stroke_u"][0])
    pre = U["kinds"]["iconset"]["icon_prefix"]
    svg_dir = os.path.join(P["export_dir"], b["id"]); os.makedirs(svg_dir, exist_ok=True)
    for f in os.listdir(svg_dir):
        if f.endswith(".svg"): os.remove(os.path.join(svg_dir, f))
    icons = {}
    for n, g in sorted(G.items()):
        fn = pre + n + ".svg"; svg = g.svg("currentColor")
        open(os.path.join(svg_dir, fn), "w").write(svg)
        icons[n] = {"svg": "%s/%s" % (b["id"], fn), "group": n.split("_")[0], **meta.get(n, {})}
    M = {x: I.load_masters(os.path.join(P["dir"], b.get("glyphs", "glyphs.py")), x) for x in IC.get("extra_px", [])}   # hand-hinted small masters (GLYPHS16)
    for x, ms in M.items():
        for n, g in sorted(ms.items()):
            if n not in icons: continue
            fn = "%s%s@%d.svg" % (pre, n, x); open(os.path.join(svg_dir, fn), "w").write(g.svg("currentColor"))
            icons[n]["svg_%d" % x] = "%s/%s" % (b["id"], fn)
    atlases = {}
    fx = b.get("variant_fx", {})          # optional per-variant raster treatment (brief): {"dilate_u": n, "grain": a}
    for var, tok in b.get("variants", IC["variants"]).items():   # a set may declare its own variants (e.g. rebel chalk + keyline)
        hexc = toks["color"][tok]
        for d in list(IC["densities"]) + ["%dpx" % x for x in IC.get("extra_px", [])]:
            px = int(d[:-2]) if isinstance(d, str) else IC["export_px"][0] * d
            pd = U["atlas"]["pad_px"] * (1 if isinstance(d, str) else d)
            ims = {n: I.raster((M.get(px, {}).get(n, g) if isinstance(d, str) else g).svg(hexc), px) for n, g in G.items()}
            rgb = (np.array(L.hex_rgb(hexc)) * 255 + 0.5).astype(np.uint8)
            for im in ims.values(): im[..., :3] = rgb        # single-ink glyphs: exact token RGB everywhere (straight alpha, bled)
            if var in fx: ims = {n: _variant_fx(im, fx[var], px / IC["grid_u"], n) for n, im in ims.items()}
            atlas, frames = I.pack_atlas(ims, px, pd, U["atlas"]["pow2"], U["atlas"]["max_px"])
            fn = "%s_%s@%s.png" % (b["id"], var, d if isinstance(d, str) else "%dx" % d); I.save_png(atlas, os.path.join(P["export_dir"], fn))
            atlases.setdefault(var, {})[str(d)] = {"image": fn, "size": [atlas.shape[1], atlas.shape[0]], "cell": px, "frames": frames, "color": tok}
    out = {"format": "ig_ui_iconset", "version": 1, "id": b["id"], "grid_u": IC["grid_u"], "px": IC["export_px"][0],
           "icons": icons, "aliases": aliases, "atlases": atlases,
           "usage": "DOM: inline the SVG (currentColor) and set CSS color from a role in ui_tokens; canvas/Babylon/Godot: atlas frame per density, pre-coloured per variant (phos on screens, ink on paper)."}
    L.write_json(P["json"], out); return out


def _variant_fx(im, f, upx, name):
    """Alpha-only treatments for a declared variant (colour untouched, so atlas.colour still holds):
    dilate_u -- grow the glyph by n grid units (a keyline drawn UNDER the main variant, for bright scenes);
    grain    -- chalk breakup: alpha x (1 - grain x streak noise), only where a grid unit is >= grain_min_px px."""
    import numpy as np, zlib
    a = im[..., 3].astype(np.float32) / 255
    r = int(round(f.get("dilate_u", 0) * upx))
    if r > 0:
        import cv2
        k = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * r + 1, 2 * r + 1)); a = cv2.dilate(a, k)
    g = f.get("grain", 0)
    if g and upx >= f.get("grain_min_px", 2):
        rs = np.random.RandomState(zlib.crc32(name.encode()) % 9973)
        h, w = a.shape; n = rs.rand(h, w).astype(np.float32)
        import cv2
        n = cv2.GaussianBlur(n, (0, 0), sigmaX=max(0.5, upx * f.get("streak", 0.9)), sigmaY=max(0.4, upx * 0.25))   # streaks run along x, a chalk stick dragged sideways
        n = (n - n.min()) / max(1e-6, n.max() - n.min())
        a = a * (1 - g * np.clip((n - 0.45) * 2.2, 0, 1))
    out = im.copy(); out[..., 3] = (np.clip(a, 0, 1) * 255 + 0.5).astype(np.uint8); return out


# --------------------------------------------------------------------------- panel / template scripts

def build_script(P):
    """Run assets/src/ui/<kind>/<id>/build_<id>.py build(ctx) in-process (pure numpy; no Blender)."""
    import importlib.util
    sp = os.path.join(P["dir"], "build_%s.py" % P["id"])
    if not os.path.exists(sp): raise SystemExit("missing %s" % sp)
    m_spec = importlib.util.spec_from_file_location("build_" + P["id"], sp); m = importlib.util.module_from_spec(m_spec); m_spec.loader.exec_module(m)
    ctx = Ctx(P); out = m.build(ctx)
    L.write_json(P["json"], out); return out


class Ctx:
    """What a panel/template build script gets."""
    def __init__(self, P):
        self.P = P; self.spec = P["spec"]; self.brief = P["brief"]; self.id = P["id"]
        self.tokens = L.load_tokens(P["root"], self.spec); self.color = self.tokens["color"]
        self.densities = self.spec["ui"]["panel"]["densities"]; self.period = self.spec["ui"]["panel"]["tile_period_px"]
        self.export_dir = P["export_dir"]; os.makedirs(self.export_dir, exist_ok=True)
        fonts = os.path.join(P["root"], self.spec["paths"]["export"], self.spec["ui"]["kinds"]["fonts"]["export_dir"])
        self.font = {"state": os.path.join(fonts, "RobotoCondensed-wght.ttf"), "typewriter": os.path.join(fonts, "CourierPrime-Regular.ttf"),
                     "typewriter_bold": os.path.join(fonts, "CourierPrime-Bold.ttf")}
        self.seed = sum(map(ord, self.id)) % 997

    def icon_svg(self, name, set_id="ui_iconset_gov"):
        pre = self.spec["ui"]["kinds"]["iconset"]["icon_prefix"]
        p = os.path.join(self.P["root"], self.spec["paths"]["export"], self.spec["ui"]["kinds"]["iconset"]["export_dir"], set_id, pre + name + ".svg")
        return open(p).read()

    def image_name(self, d): return "%s@%dx.png" % (self.id, d)

    def image_path(self, d): return os.path.join(self.export_dir, self.image_name(d))
